"""Configure, build, and install the CUDA solver with CMake, one build directory per configuration."""

import hashlib
import json
import os
import shutil

from toolchain import parameters
from toolchain.computers import computer_name, load_environment
from toolchain.progress import run_with_progress

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD_ROOT = os.path.join(REPO_ROOT, "build")


def _cpp_literal(value):
    if isinstance(value, bool):
        return "bool", "true" if value else "false"
    if isinstance(value, int):
        return "int", str(value)
    return "double", repr(float(value))


def case_header(case):
    """C++ header with the case optimized parameters as constexpr values."""
    values = {name: case[name] for name in parameters.CASE_OPTIMIZATION}
    lines = ["// generated by toolchain/build.py, do not edit", "#ifndef CASE_PARAMETERS_HPP", "#define CASE_PARAMETERS_HPP", "",
             "namespace case_parameters {"]
    for name, value in values.items():
        cpp_type, literal = _cpp_literal(value)
        lines.append(f"constexpr {cpp_type} {name} = {literal};")
    summary = ", ".join(f"{name} = {_cpp_literal(value)[1]}" for name, value in values.items())
    lines += [f'constexpr const char* summary = "{summary}";', "}  // namespace case_parameters", "", "#endif", ""]
    return "\n".join(lines)


def build_configuration(case, computer, debug):
    """Everything that changes the binary; its hash names the build directory."""
    return {"case_optimization": None if case is None else {name: case[name] for name in parameters.CASE_OPTIMIZATION},
            "computer": computer_name(computer),
            "build_type": "Debug" if debug else "Release"}


def _write_if_changed(path, content):
    """Leave the file untouched when the content is the same, so CMake does not rebuild."""
    if os.path.isfile(path) and open(path).read() == content:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as output_file:
        output_file.write(content)


def build(case=None, computer=None, jobs=8, debug=False, verbose=False):
    """Build the solver, case optimized when a case is given, and return the installed executable path."""
    environment = load_environment(computer)
    for tool in ("cmake", "nvcc"):
        assert shutil.which(tool, path=environment.get("PATH")), f"ERROR :: {tool} not found, load a compiler environment with -c"

    configuration = build_configuration(case, computer, debug)
    slug = hashlib.sha256(json.dumps(configuration, sort_keys=True).encode()).hexdigest()[:10]
    staging_dir = os.path.join(BUILD_ROOT, "staging", slug)
    install_dir = os.path.join(BUILD_ROOT, "install", slug)
    header_dir = os.path.join(staging_dir, "include")
    _write_if_changed(os.path.join(staging_dir, "configuration.json"), json.dumps(configuration, indent=4) + "\n")
    if case is not None:
        _write_if_changed(os.path.join(header_dir, "case_parameters.hpp"), case_header(case))

    kind = "case optimized" if case is not None else "generic"
    print(f"INFO :: {kind} {configuration['build_type']} build for {configuration['computer']} in build/staging/{slug}")
    configure_command = ["cmake", "-S", REPO_ROOT, "-B", staging_dir, f"-DCMAKE_BUILD_TYPE={configuration['build_type']}",
                         f"-DCMAKE_INSTALL_PREFIX={install_dir}",
                         f"-DCMAKE_CUDA_ARCHITECTURES={environment.get('CTM_CUDA_ARCHITECTURES', 'native')}",
                         f"-DCTM_CASE_OPTIMIZATION={'ON' if case is not None else 'OFF'}", f"-DCTM_CASE_HEADER_DIR={header_dir}"]
    run_with_progress(configure_command, "Configuring", environment, verbose)
    run_with_progress(["cmake", "--build", staging_dir, "--parallel", str(jobs)], "Building", environment, verbose)
    run_with_progress(["cmake", "--install", staging_dir], "Installing", environment, verbose)
    return os.path.join(install_dir, "bin", "simulation")
